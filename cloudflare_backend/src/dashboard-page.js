  "/**",
  " * 把当前背景图压到合适大小再上传：长边最多 1600px，优先 WebP。",
  " * 关卡截图动辄 2~4 MB，压完一般 80~250 KB，KV 的 1 GB 能放几千张。",
  " */",
  "async function encodeBgForUpload(blob) {",
  "  const img = await decodeImage(URL.createObjectURL(blob));",
  "  const maxSide = 1600;",
  "  const scale = Math.min(1, maxSide / Math.max(img.naturalWidth, img.naturalHeight));",
  "  const w = Math.max(1, Math.round(img.naturalWidth * scale));",
  "  const h = Math.max(1, Math.round(img.naturalHeight * scale));",
  "",
  "  const canvas = document.createElement(\"canvas\");",
  "  canvas.width = w;",
  "  canvas.height = h;",
  "  const ctx = canvas.getContext(\"2d\");",
  "  ctx.drawImage(img, 0, 0, w, h);",
  "",
  "  let quality = 0.85;",
  "  let data = canvas.toDataURL(\"image/webp\", quality);",
  "  if (!data.startsWith(\"data:image/webp\")) {",
  "    // 老浏览器不支持 WebP 编码，退回 JPEG（背景图不需要透明）",
  "    data = canvas.toDataURL(\"image/jpeg\", quality);",
  "  }",
  "  // 还是太大就继续降质量，最多试 3 次",
  "  for (let i = 0; i < 3 && data.length > 2.5 * 1024 * 1024; i++) {",
  "    quality -= 0.2;",
  "    data = data.startsWith(\"data:image/webp\")",
  "      ? canvas.toDataURL(\"image/webp\", quality)",
  "      : canvas.toDataURL(\"image/jpeg\", quality);",
  "  }",
  "  return { data, w, h };",
  "}",
