  "// 客户端现在是\"每帧进入新格子就记一格\"，正常移动相邻两格一定是挨着的。",
  "// 只有极快移动（下落冲刺）或旧版本 0.1 秒采样的数据才会隔开几格：",
  "// 隔 1~4 格补成直线还算忠实（一帧内确实是从 A 直着飞到 B），",
  "// 隔得更多就说明中间那几个格子没采到，硬连会画出\"斜穿地图\"的假路线 —— 直接断开不连。",
  "function densifyRoute(cells) {",
  "  const out = [];",
  "  const seen = new Set();",
  "  const push = (x, y) => {",
  "    const k = x + \",\" + y;",
  "    if (seen.has(k)) return;",
  "    seen.add(k);",
  "    out.push([x, y]);",
  "  };",
  "  for (let i = 0; i < cells.length; i++) {",
  "    const [x1, y1] = cells[i];",
  "    push(x1, y1);",
  "    const nxt = cells[i + 1];",
  "    if (!nxt) break;",
  "    const [x2, y2] = nxt;",
  "    let dx = Math.abs(x2 - x1);",
  "    let dy = Math.abs(y2 - y1);",
  "    if (dx + dy > 4) continue; // 采集中断 / 传送 / 重生：不连，别编造路径",
  "    const sx = x1 < x2 ? 1 : -1;",
  "    const sy = y1 < y2 ? 1 : -1;",
  "    let err = dx - dy;",
  "    let cx = x1;",
