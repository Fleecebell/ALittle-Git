  "// 每个角色只取最新一条（按接口给的倒序）",
  "function perActorLatest(list) {",
  "  const seen = new Set();",
  "  const out = [];",
  "  for (const r of list) {",
  "    const who = r.actor || \"player1\";",
  "    if (seen.has(who)) continue;",
  "    seen.add(who);",
  "    out.push(r);",
  "  }",
  "  return out;",
